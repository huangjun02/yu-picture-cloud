-- ============================================================
-- 云图库 yu-picture-cloud · 图片表加 MD5 指纹（秒传）
-- 执行前提：05_create_table_image.sql（及 06~11）已执行
-- 幂等性：⚠️ MySQL 的 ADD COLUMN 没有 IF NOT EXISTS，重复执行会报 Duplicate column —— 执行前先看列在不在。
-- ============================================================

USE yu_picture_cloud;

-- MD5 指纹：对「压缩后最终落库的内容」计算的字节级精确指纹。
-- 为什么 CHAR(32)：128 位 → 32 个十六进制字符，定长不多占空间。
-- 为什么 NULL 允许：秒传功能上线前传的存量图没有指纹（老图照常上传，只是不参与秒传命中）；
--   与 picHash / picColor 同一条纪律 —— 派生信息缺失不连坐主流程。
ALTER TABLE `image`
    ADD COLUMN md5 CHAR(32) NULL COMMENT '内容 MD5 指纹（32 位小写十六进制，秒传去重键）' AFTER picHash;

-- 普通索引（不是唯一索引）的两个作用：
-- ① 秒传查询「有没有同指纹的图」走索引等值命中，O(log n)。
-- ② 为什么不能是唯一索引：秒传的归属语义是「B 传 A 已有图 → 新记录挂 B 名下、复用 COS 对象」，
--    A、B 两条记录的 md5 天然相同，唯一索引会直接禁止第二条落库 —— 与归属方案互斥。
--    并发的「查-插」竞态在普通索引下的最坏结果：两个请求都没查到对方、各传一份存储、各落一条记录
--    —— 无错误无丢数据，只是极端并发下少省一次存储，可接受；换来的是多归属模型成立。
-- md5 为 NULL 的行不参与索引去重语义（普通索引本来就允许重复），存量图与失败降级的图互不冲突。
ALTER TABLE `image`
    ADD KEY idx_md5 (md5);
